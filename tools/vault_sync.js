// Write the asset pages of the Obsidian brain from the indexes, so agents (and the owner) can see every asset.
// Usage: node tools/vault_sync.js   → brain/assets/cast.md, brain/assets/fx.md, brain/assets/music.md
const fs = require("fs"), path = require("path");
const ROOT = path.resolve(__dirname, ".."), out = (f, s) => fs.writeFileSync(path.join(ROOT, "brain/assets", f), s);
const idx = JSON.parse(fs.readFileSync(path.join(ROOT, "library/cast/index.json"), "utf8"));
const page = (title, ids) => `# ${title}\n\n_Generated by \`node tools/vault_sync.js\` — do not edit by hand._\n\n` +
  ids.map((id) => `## ${id}\n${idx[id].desc} · faces **${idx[id].faces || "?"}** · ${idx[id].size.join("×")}\n\n![[${idx[id].file}|180]]\n`).join("\n");
const ids = Object.keys(idx);
out("cast.md", page("Cast stills", ids.filter((i) => !i.startsWith("fx/"))));
out("fx.md", page("Graphics (fx)", ids.filter((i) => i.startsWith("fx/"))));
const music = JSON.parse(fs.readFileSync(path.join(ROOT, "library/music/index.json"), "utf8"));
out("music.md", "# Music\n\n| id | title | creator | licence | source |\n|---|---|---|---|---|\n" +
  Object.entries(music).map(([k, m]) => `| ${k} | ${m.title} | ${m.creator} | ${m.licence} | ${m.page} |`).join("\n") + "\n\nIn use: `chill-hiphop-klaudux`.\n");
console.log(`synced ${ids.length} assets`);
